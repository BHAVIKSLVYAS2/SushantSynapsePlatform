const {test}=require('node:test');
const assert=require('node:assert/strict');
const {startPreview}=require('./organisation-preview-fixture.cjs');
test('suspension affects existing sessions and only reactivation with a valid licence restores scoped access',async t=>{
 const f=await startPreview({chambers:true,multi:true});t.after(f.stop);
 const master=await f.login('master'),superCookie=await f.login('super'),client=await f.login('client');
 const org='/api/organisation-admin/organisations/'+f.organisationId;
 const get=(path,cookie=master)=>fetch(f.base+path,{headers:{Cookie:cookie}});
 const post=(path,body,cookie=superCookie)=>fetch(f.base+path,{method:'POST',headers:{Cookie:cookie,'Content-Type':'application/json'},body:JSON.stringify(body)});
 const view=async()=>await(await get(org,superCookie)).json();
 const licenceFields=row=>Object.fromEntries(['appId','startsAt','endsAt','readOnlyUntil','staffLimit','clientLimit'].map(key=>[key,row[key]]));
 let v=await view();
 const pending=await(await post(org+'/invite',{email:'client@example.com',role:'Client',version:v.organisation.version,reason:'Pending client'},master)).json();
 v=await view();const change={status:'Suspended',confirmation:v.organisation.name,version:v.organisation.version,reason:'Suspend for investigation'};
 assert.equal((await post(org+'/status',change,master)).status,403);
 assert.equal((await post(org+'/status',{...change,actorUserId:'super'},master)).status,400);
 assert.equal((await post(org+'/status',change)).status,200);
 assert.equal((await post(org+'/status',change)).status,409);
 for(const operation of ['state','backup','files/guessed'])assert.equal((await get('/api/chambers/'+f.organisationId+'/'+operation)).status,403);
 assert.equal((await post('/api/chambers/'+f.organisationId+'/clients',{name:'Blocked'},master)).status,403);
 assert.equal((await get('/api/chambers/'+f.otherOrganisationId+'/state')).status,200);
 assert.equal((await get(org)).status,403);
 assert.equal((await post('/api/organisation-admin/accept',{primary:false,token:pending.invitation.token},client)).status,400);
 const account=await(await get('/api/organisation-admin/account')).json();assert.equal(account.memberships.find(m=>m.id===f.organisationId).apps[0].available,false);
 v=await view();const l=v.organisation.licences[0];
 assert.equal((await post(org+'/licence',{...licenceFields(l),status:'Suspended',version:v.organisation.version,licenceVersion:l.version,reason:'Keep app licence suspended'})).status,200);
 v=await view();assert.equal((await post(org+'/status',{status:'Active',confirmation:v.organisation.name,version:v.organisation.version,reason:'Organisation cleared'})).status,200);
 assert.equal((await get(org)).status,200);assert.equal((await get('/api/chambers/'+f.organisationId+'/state')).status,403);
 assert.equal((await post('/api/organisation-admin/accept',{primary:false,token:pending.invitation.token},client)).status,200);
 v=await view();const current=v.organisation.licences[0];
 assert.equal((await post(org+'/licence',{...licenceFields(current),status:'Active',version:v.organisation.version,licenceVersion:current.version,reason:'Restore current licence'})).status,200);
 assert.equal((await get('/api/chambers/'+f.organisationId+'/state')).status,200);
});
